function router() {
  const parts = routeParts();
  const [section, id] = parts;
  document.body.classList.remove('menu-open');
  if (section === 'home') return renderHome();
  if (section === 'percorso') return renderPercorso();
  if (section === 'lezioni') return renderLezioni($('#searchInput')?.value || '');
  if (section === 'lezione') return renderLesson(id);
  if (section === 'mappe') return renderMappe();
  if (section === 'quiz') return renderQuiz();
  if (section === 'materiali') return renderMateriali();
  renderHome();
}

