function renderQuiz() {
  let answered = Array(quiz.length).fill(null);
  page('Verifica', `
    <div class="section-heading"><div><span class="eyebrow">Verifica formativa</span><h2>Quiz su Svevo e Zeno</h2></div><button id="resetQuiz" class="pill-button">Ricomincia</button></div>
    <div class="grid two" id="quizGrid">${quiz.map((item, i) => quizCard(item, i)).join('')}</div>
    <section class="section score-box"><h3 id="scoreTitle">Risultato: 0/${quiz.length}</h3><p id="scoreText">Rispondi alle domande: il risultato si aggiorna subito.</p></section>
  `);
  $$('.option').forEach(btn => btn.addEventListener('click', () => {
    const card = btn.closest('.quiz-card');
    const qi = Number(card.dataset.q);
    const oi = Number(btn.dataset.o);
    if (answered[qi] !== null) return;
    answered[qi] = oi;
    $$('.option', card).forEach(opt => {
      const idx = Number(opt.dataset.o);
      if (idx === quiz[qi].a) opt.classList.add('correct');
      if (idx === oi && oi !== quiz[qi].a) opt.classList.add('wrong');
      opt.disabled = true;
    });
    $('.quiz-feedback', card).textContent = quiz[qi].why;
    updateScore(answered);
  }));
  $('#resetQuiz').addEventListener('click', renderQuiz);
}
function quizCard(item, i) {
  return `<article class="quiz-card" data-q="${i}"><span class="eyebrow">Quesito ${i+1}</span><h3>${escapeHtml(item.q)}</h3><div class="quiz-options">${item.options.map((o, idx) => `<button class="option" data-o="${idx}">${escapeHtml(o)}</button>`).join('')}</div><p class="quiz-feedback"></p></article>`;
}
function updateScore(answered) {
  const done = answered.filter(v => v !== null).length;
  const score = answered.reduce((acc, v, i) => acc + (v === quiz[i].a ? 1 : 0), 0);
  $('#scoreTitle').textContent = `Risultato: ${score}/${quiz.length}`;
  $('#scoreText').textContent = done === quiz.length ? (score >= 8 ? 'Ottimo: puoi passare a una risposta argomentativa.' : 'Rivedi le lezioni collegate agli errori e ripeti la verifica.') : `Hai risposto a ${done} domande su ${quiz.length}.`;
}

